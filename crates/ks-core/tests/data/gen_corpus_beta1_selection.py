#!/usr/bin/env python3
"""Generates corpus_beta1_selection.tsv: D-31 selection-mode expectations for ks-core.

Run from the repository root:  python3 crates/ks-core/tests/data/gen_corpus_beta1_selection.py
Inputs are the inputs of corpus_beta1.tsv (synthetic text only). The expected value is the
D-31 rule applied independently of ks-core: every character key for key through the
layouts (same scan code, same Shift state), except `.` `,` `:` between two digits. Inputs
with letters of both languages (popup) or without letters are left out.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[4]
DATA = ROOT / "crates/ks-core/tests/data"
LAYOUTS = ROOT / "crates/ks-core/layouts"


def load(name):
    to_char, to_key = {}, {}
    for line in (LAYOUTS / name).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        sc, base, shift = line.split()
        for sh, ch in ((False, base), (True, shift)):
            to_char[(sc, sh)] = ch
            to_key.setdefault(ch, (sc, sh))
    return to_char, to_key


EN, RU = load("en-us.layout"), load("ru.layout")


def lang(text):
    en = any("a" <= c.lower() <= "z" for c in text)
    ru = any("а" <= c.lower() <= "я" or c.lower() == "ё" for c in text)
    return {(True, False): "en", (False, True): "ru"}.get((en, ru))


def literal(text, src, tgt):
    out = []
    for i, c in enumerate(text):
        between = 0 < i < len(text) - 1 and text[i - 1].isdigit() and text[i + 1].isdigit()
        if c in ".,:" and between:
            out.append(c)
            continue
        key = src[1].get(c)
        out.append(tgt[0].get(key, c) if key else c)
    return "".join(out)


def main():
    rows = []
    for line in (DATA / "corpus_beta1.tsv").read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        cat, inp, _ = line.split("\t")
        lng = lang(inp)
        if lng is None:
            continue
        src, tgt = (EN, RU) if lng == "en" else (RU, EN)
        rows.append(f"sel_{cat}\t{inp}\t{literal(inp, src, tgt)}")
    head = [
        "# D-31 selection-mode corpus. Generated by gen_corpus_beta1_selection.py - do not edit.",
        "# Synthetic test data only. Columns: category<TAB>input<TAB>expected",
    ]
    (DATA / "corpus_beta1_selection.tsv").write_text(
        "\n".join(head + rows) + "\n", encoding="utf-8"
    )


main()
